"""AKI outcome labels after T for baselines A and C (HANDOFF step 2).

Outcome: KDIGO stage >= 1 with onset after T, where onset is the first
creatinine draw after T that meets a criterion. Stays in the final cohort have
no qualifying draw at or before T (they were excluded), so for them "first
qualifying draw" and "first qualifying draw after T" are the same thing.

Usage:
    python -m polysafe.labels     # writes results/aki_labels.md and results/labels_{A,C}.csv
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import pandas as pd

from polysafe import cohort
from polysafe.cohort import T_MIN


def onsets(cr: pd.DataFrame, baseline: pd.DataFrame) -> pd.DataFrame:
    """First qualifying draw after T per stay: offset and which criterion it met."""
    h = cohort.kdigo_hits(cr, baseline)
    h = h[h["offset"] > T_MIN]
    first = h.groupby("patientunitstayid").first()
    first["criterion"] = (first["rise"].map({True: "rise", False: ""})
                          + (first["rise"] & first["ratio"]).map({True: "+", False: ""})
                          + first["ratio"].map({True: "ratio", False: ""}))
    return first[["offset", "criterion"]]


def label(tables: dict[str, pd.DataFrame], baseline: str):
    """Returns (labelled cohort, flow, set of all stays with an event after T)."""
    cr = cohort.serum_creatinine(tables["lab"])
    on = onsets(cr, cohort.BASELINES[baseline](cr))
    final, flow = cohort.build_cohort(tables, baseline=baseline)
    out = final[["patientunitstayid", "hospitalid", "uniquepid"]].join(
        on.rename(columns={"offset": "onset_offset"}), on="patientunitstayid")
    out.insert(1, "aki", out["onset_offset"].notna())
    return out, flow, set(on.index)


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """Wilson score 95% interval for a proportion."""
    if n == 0:
        return (math.nan, math.nan)
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return (centre - half, centre + half)


def pct(k: int, n: int) -> str:
    return f"{100 * k / n:.1f}%" if n else "-"


def report(tables: dict[str, pd.DataFrame]) -> tuple[str, dict[str, pd.DataFrame]]:
    lines = ["# AKI labels (generated by `python -m polysafe.labels`)", "",
             f"T = {T_MIN // 60} h. Outcome = KDIGO stage >= 1 with onset after T "
             "(>= 0.3 mg/dL rise within 48 h, or >= 1.5x baseline within 7 days of it). "
             "Serum creatinine only.", ""]
    labelled = {}
    cr = cohort.serum_creatinine(tables["lab"])
    # DATA_REPORT's provisional "22.6%": any 48 h rise anywhere in the record.
    provisional = set(cohort.kdigo_hits(cr, cohort.baseline_a(cr).iloc[0:0])["patientunitstayid"])
    two_draws = (cr.groupby("patientunitstayid").size() >= 2).sum()

    for b in ("A", "C"):
        out, flow, events = label(tables, b)
        labelled[b] = out
        lines += [f"## Baseline {b}", "",
                  "| Step | Removed | Remaining | Events in remaining | Event rate | Reason |",
                  "|---|---:|---:|---:|---:|---|"]
        for s in flow:
            k = len(s.remaining & events)
            removed = "" if s.name == "Start" else f"{len(s.removed):,}"
            lines.append(f"| {s.name} | {removed} | {len(s.remaining):,} | {k:,} | "
                         f"{pct(k, len(s.remaining))} | {s.reason} |")
        n, k = len(out), int(out["aki"].sum())
        lo, hi = wilson(k, n)
        pos = out[out["aki"]]
        hours = (pos["onset_offset"] - T_MIN) / 60
        lines += ["", f"**Incidence: {k:,} / {n:,} = {pct(k, n)}** "
                      f"(95% Wilson CI {100 * lo:.1f}-{100 * hi:.1f}%), "
                      f"{out['hospitalid'].nunique()} hospitals, "
                      f"{out['uniquepid'].nunique():,} patients.", "",
                  "Criterion met at onset: " + ", ".join(
                      f"{c} {v}" for c, v in pos["criterion"].value_counts().items()) + ".",
                  f"Hours from T to onset: median {hours.median():.1f}, "
                  f"IQR {hours.quantile(0.25):.1f}-{hours.quantile(0.75):.1f}.", ""]
        if b == "A":
            lines += ["DATA_REPORT's provisional 22.6% (465 / 2,058) counted any 48 h rise "
                      "anywhere in the record, with no T, no exclusions and no baseline. "
                      f"Recounted here: {len(provisional):,} / {two_draws:,}. The extra stays "
                      "are rises of exactly 0.3 mg/dL that the provisional script missed "
                      "through floating-point rounding (e.g. 2.3 - 2.0 = 0.2999...). "
                      "Where those stays went:", ""]
            for s in flow[1:]:
                lines.append(f"- removed at *{s.name}*: {len(s.removed & provisional):,}")
            left = flow[-1].remaining & provisional
            lines += [f"- still in the final cohort: {len(left):,}, of which labelled AKI "
                      f"after T: {len(left & events):,}", ""]

    a, c = labelled["A"].set_index("patientunitstayid"), labelled["C"].set_index(
        "patientunitstayid")
    both = a.index.intersection(c.index)
    xt = pd.crosstab(a.loc[both, "aki"], c.loc[both, "aki"])
    agree = int(xt.values.trace())
    lines += ["## Baseline A vs C", "",
              f"{len(both):,} stays are labelled under both baselines; "
              f"they agree on {agree:,} ({pct(agree, len(both))}).", "",
              "| | C: no AKI | C: AKI |", "|---|---:|---:|",
              f"| **A: no AKI** | {xt.loc[False, False]:,} | {xt.loc[False, True]:,} |",
              f"| **A: AKI** | {xt.loc[True, False]:,} | {xt.loc[True, True]:,} |", ""]
    return "\n".join(lines), labelled


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Label AKI after T for baselines A and C.")
    p.add_argument("--out", type=Path, default=Path("results"))
    args = p.parse_args(argv)

    md, labelled = report(cohort.load_inputs())
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "aki_labels.md").write_text(md, encoding="utf-8")
    for b, df in labelled.items():
        df.to_csv(args.out / f"labels_{b}.csv", index=False)
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
