"""AKI outcome labels for baselines A and C (PREREGISTRATION section 4, D1.3).

Outcome: KDIGO stage >= 1 with onset in the window (T, end], end = min(T + 7 d,
ICU discharge or death), met by either
  - a creatinine draw in the window that meets the 48 h rise or the 1.5x
    baseline rule (``cohort.kdigo_hits``), or
  - initiation of acute RRT in the window (KDIGO stage 3).
Onset is the earliest of these.

Usage:
    python -m polysafe.labels   # writes results/cohort_flow.md, results/aki_labels.md,
                                #        results/labels_{A,C}.csv
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import pandas as pd

from polysafe import cohort
from polysafe.cohort import T_MIN


def onsets(cr: pd.DataFrame, baseline: pd.DataFrame, rrt: pd.Series,
           end: pd.Series) -> pd.DataFrame:
    """First qualifying event in (T, end] per stay: offset and the criterion (or criteria) met."""
    h = cohort.kdigo_hits(cr, baseline)
    h = h[cohort.in_window(h.set_index("patientunitstayid")["offset"], end).to_numpy()]
    first = h.groupby("patientunitstayid").first()
    df = pd.DataFrame({"cr": first["offset"], "rrt": rrt[cohort.in_window(rrt, end)]})
    df["offset"] = df[["cr", "rrt"]].min(axis=1)
    rise = first["rise"].reindex(df.index, fill_value=False)
    ratio = first["ratio"].reindex(df.index, fill_value=False)
    at_cr = df["cr"] == df["offset"]
    parts = pd.DataFrame({"rise": at_cr & rise, "ratio": at_cr & ratio,
                          "rrt": df["rrt"] == df["offset"]})
    df["criterion"] = parts.apply(lambda r: "+".join(c for c in parts.columns if r[c]), axis=1)
    return df[["offset", "criterion"]]


def label(tables: dict[str, pd.DataFrame], baseline: str):
    """Returns (labelled cohort, flow, set of all stays with an event in their window)."""
    patient = tables["patient"]
    cr = cohort.serum_creatinine(tables["lab"])
    end = cohort.outcome_end(patient)
    on = onsets(cr, cohort.BASELINES[baseline](cr), cohort.rrt_start(tables["treatment"]), end)
    final, flow = cohort.build_cohort(tables, baseline=baseline)
    sites = cohort.recording_hospitals(patient, tables["medication"])

    out = final[["patientunitstayid", "uniquepid", "hospitalid"]].copy()
    out["primary_site"] = out["hospitalid"].isin(sites)  # population filter, NOT a predictor
    out["followup_h"] = (end.reindex(out["patientunitstayid"]).to_numpy() - T_MIN) / 60
    out = out.join(on.rename(columns={"offset": "onset_offset"}), on="patientunitstayid")
    out.insert(1, "aki", out["onset_offset"].notna())
    return out.reset_index(drop=True), flow, set(on.index)


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """Wilson score 95% interval for a proportion."""
    if n == 0:
        return (math.nan, math.nan)
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return (centre - half, centre + half)


def pct(k: int, n: int) -> str:
    return f"{100 * k / n:.1f}%" if n else "-"


def rate(df: pd.DataFrame) -> str:
    n, k = len(df), int(df["aki"].sum())
    lo, hi = wilson(k, n)
    return f"{k:,} / {n:,} = **{pct(k, n)}** ({100 * lo:.1f}-{100 * hi:.1f}%)"


def flow_markdown(results: dict, patients: pd.Series) -> str:
    lines = ["# Cohort flow (generated by `python -m polysafe.labels`)", "",
             "Events = AKI with onset in (T, min(T + 7 d, ICU discharge)], by creatinine or "
             "acute RRT, among the stays remaining after each step.", ""]
    for b, (out, flow, events) in results.items():
        lines += [f"## Baseline {b}", "",
                  "| Step | Removed | Stays | Patients | Events | Event rate | Reason |",
                  "|---|---:|---:|---:|---:|---:|---|"]
        for s in flow:
            k = len(s.remaining & events)
            removed = "" if s.name == "Start" else f"{len(s.removed):,}"
            pts = patients.loc[sorted(s.remaining)].nunique()
            lines.append(f"| {s.name} | {removed} | {len(s.remaining):,} | {pts:,} | {k:,} | "
                         f"{pct(k, len(s.remaining))} | {s.reason} |")
        prim = out[out["primary_site"]]
        lines.append(f"| **Primary estimand: medication-recording sites** | "
                     f"{len(out) - len(prim):,} | **{len(prim):,}** | "
                     f"{prim['uniquepid'].nunique():,} | "
                     f"{int(prim['aki'].sum()):,} | {pct(int(prim['aki'].sum()), len(prim))} | "
                     "site-level restriction (section 6); not a predictor |")
        lines.append("")
    return "\n".join(lines)


def labels_markdown(results: dict, provisional: set, two_draws: int) -> str:
    lines = ["# AKI labels (generated by `python -m polysafe.labels`)", "",
             f"T = {T_MIN // 60} h. AKI = KDIGO stage >= 1 with onset in (T, min(T + 7 d, ICU "
             "discharge)]: >= 0.3 mg/dL rise within 48 h, >= 1.5x baseline within 7 days of it, "
             "or acute RRT initiation. Serum creatinine only.", "",
             "## Incidence (95% Wilson CI)", "",
             "| Baseline | All sites | Primary: medication-recording sites |", "|---|---|---|"]
    for b in ("A", "C"):
        out = results[b][0]
        lines.append(f"| {b} | {rate(out)} | {rate(out[out['primary_site']])} |")

    for b in ("A", "C"):
        out = results[b][0]
        pos = out[out["aki"]]
        fu = out["followup_h"]
        h = (pos["onset_offset"] - T_MIN) / 60
        long = out[fu >= 48]
        lines += ["", f"## Baseline {b}", "",
                  "Criterion at onset: " + ", ".join(
                      f"{c} {v}" for c, v in pos["criterion"].value_counts().items()) + ".",
                  f"Hours from T to onset: median {h.median():.1f} "
                  f"(IQR {h.quantile(0.25):.1f}-{h.quantile(0.75):.1f}).", "",
                  "Post-T follow-up, hours from T to min(T + 7 d, ICU discharge):", "",
                  "| min | 25% | median | 75% | max | >= 48 h | reached 7 d |",
                  "|---:|---:|---:|---:|---:|---:|---:|",
                  f"| {fu.min():.1f} | {fu.quantile(.25):.1f} | {fu.median():.1f} | "
                  f"{fu.quantile(.75):.1f} | {fu.max():.1f} | {int((fu >= 48).sum()):,} "
                  f"({pct(int((fu >= 48).sum()), len(fu))}) | "
                  f"{int((fu >= 168).sum()):,} |", "",
                  f"Sensitivity (>= 48 h follow-up): all sites {rate(long)}; "
                  f"primary sites {rate(long[long['primary_site']])}."]

    out_a, flow_a, ev_a = results["A"]
    left = flow_a[-1].remaining & provisional
    lines += ["", "## Against DATA_REPORT's provisional 22.6%", "",
              "The provisional figure (465 / 2,058) counted any 48 h rise anywhere in the record: "
              "no T, no exclusions, no baseline, no window. Recounted with the floating-point "
              f"fix it is {len(provisional):,} / {two_draws:,}. Where those stays went "
              "(baseline A):", ""]
    for s in flow_a[1:]:
        lines.append(f"- removed at *{s.name}*: {len(s.removed & provisional):,}")
    lines += [f"- in the final cohort: {len(left):,}, of which AKI in the window: "
              f"{len(left & ev_a):,}", ""]

    a = results["A"][0].set_index("patientunitstayid")
    c = results["C"][0].set_index("patientunitstayid")
    both = a.index.intersection(c.index)
    xt = pd.crosstab(a.loc[both, "aki"], c.loc[both, "aki"]).reindex(
        index=[False, True], columns=[False, True], fill_value=0)
    agree = int(xt.values.trace())
    lines += ["## Baseline A vs C", "",
              f"{len(both):,} stays are labelled under both; they agree on {agree:,} "
              f"({pct(agree, len(both))}).", "",
              "| | C: no AKI | C: AKI |", "|---|---:|---:|",
              f"| **A: no AKI** | {xt.loc[False, False]:,} | {xt.loc[False, True]:,} |",
              f"| **A: AKI** | {xt.loc[True, False]:,} | {xt.loc[True, True]:,} |", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Label AKI for baselines A and C.")
    p.add_argument("--out", type=Path, default=Path("results"))
    args = p.parse_args(argv)

    tables = cohort.load_inputs()
    results = {b: label(tables, b) for b in ("A", "C")}
    cr = cohort.serum_creatinine(tables["lab"])
    # DATA_REPORT's provisional count: any 48 h rise anywhere (no baseline, no T, no window).
    provisional = set(cohort.kdigo_hits(cr, cohort.baseline_a(cr).iloc[0:0])["patientunitstayid"])
    two_draws = int((cr.groupby("patientunitstayid").size() >= 2).sum())

    args.out.mkdir(parents=True, exist_ok=True)
    patients = tables["patient"].set_index("patientunitstayid")["uniquepid"]
    flow_md = flow_markdown(results, patients)
    labels_md = labels_markdown(results, provisional, two_draws)
    (args.out / "cohort_flow.md").write_text(flow_md, encoding="utf-8")
    (args.out / "aki_labels.md").write_text(labels_md, encoding="utf-8")
    for b, (out, _, _) in results.items():
        out.to_csv(args.out / f"labels_{b}.csv", index=False)
    print(flow_md, "\n", labels_md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
