"""D12.1: the reported final model (coefficients) and calibration intervals.

Reporting only: the D7.2 primary specification is fitted once on all 671 primary-cohort
stays with the most often tuned C. Its apparent performance is never computed. Calibration
intercept and slope of the pooled out-of-fold predictions get patient-level BCa intervals.

Usage:
    python -m polysafe.final_model    # writes results/final_model*.csv and .md
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression

from polysafe import bootstrap, models

RESULTS = Path("results")


def chosen_c(tuning: pd.DataFrame, medication: bool) -> float:
    """Most often chosen C across the outer folds; ties to the smaller C (D12.1)."""
    t = tuning[(tuning["spec"] == "lr_reduced") & (tuning["medication"] == medication)]
    counts = t["param"].astype(float).value_counts()
    top = counts[counts == counts.max()].index
    return float(min(top))


def design_names(spec: models.Spec, medication: bool) -> list[str]:
    names = list(spec.clinical) + [f"missing({'+'.join(g)})" for g in spec.indicators]
    return names + (list(models.MED_COLS) if medication else [])


def fit_final(X: pd.DataFrame, y: np.ndarray, spec: models.Spec, medication: bool,
              c: float) -> pd.DataFrame:
    z, _ = models.lr_design(X, X.iloc[:1], spec, medication)
    raw_cols = list(spec.clinical)
    tr = X[raw_cols].astype(float)
    model = LogisticRegression(C=c, solver="lbfgs", max_iter=10_000).fit(z, y)
    names = design_names(spec, medication)
    if len(names) != z.shape[1]:
        raise RuntimeError("design columns and names differ")
    # the unstandardised design, to report the centring and scaling used
    parts = [tr.fillna(tr.median())]
    parts += [tr[list(g)].isna().any(axis=1).astype(float) for g in spec.indicators]
    if medication:
        m = X[list(models.MED_COLS)].astype(float)
        parts.append(m.fillna(m.mean()))
    x = pd.concat(parts, axis=1).to_numpy(float)
    median = list(tr.median()) + [np.nan] * (len(names) - len(raw_cols))
    rows = [{"term": "(intercept)", "coefficient": float(model.intercept_[0]),
             "or_per_sd": np.nan, "impute_median": np.nan, "mean": np.nan, "sd": np.nan}]
    for k, name in enumerate(names):
        b = float(model.coef_[0][k])
        rows.append({"term": name, "coefficient": b, "or_per_sd": float(np.exp(b)),
                     "impute_median": median[k], "mean": float(x[:, k].mean()),
                     "sd": float(x[:, k].std())})
    return pd.DataFrame(rows).assign(model="clinical + medication" if medication
                                     else "clinical only", C=c)


def calibration_intervals(preds: pd.DataFrame, y: np.ndarray, groups: np.ndarray,
                          n_boot: int = bootstrap.N_BOOT) -> pd.DataFrame:
    rows = []
    for spec in ("lr_reduced", "lgbm"):
        for med in (False, True):
            p = preds[f"p_{spec}_{'medication' if med else 'clinical'}"].to_numpy(float)
            icpt, slope = models.calibration(p, y)
            ci_i = models.interval(lambda i, p=p: models.calibration(p[i], y[i])[0], groups,
                                   n_boot)
            ci_s = models.interval(lambda i, p=p: models.calibration(p[i], y[i])[1], groups,
                                   n_boot)
            rows.append({"spec": spec, "medication": med, "cal_intercept": icpt,
                         "intercept_lo": ci_i["lo"], "intercept_hi": ci_i["hi"],
                         "cal_slope": slope, "slope_lo": ci_s["lo"], "slope_hi": ci_s["hi"]})
    return pd.DataFrame(rows)


def run(results: Path) -> int:
    X, y, groups = models.load_data(results)
    spec = models.specs([c for c in X.columns if c not in models.MED_COLS])[0]
    tuning = pd.read_csv(results / "model_tuning.csv")
    coef = pd.concat([fit_final(X, y, spec, med, chosen_c(tuning, med))
                      for med in (False, True)], ignore_index=True)
    coef.to_csv(results / "final_model.csv", index=False)
    preds = pd.read_csv(results / "model_predictions.csv").set_index("patientunitstayid")
    cal = calibration_intervals(preds.loc[X.index], y, groups)
    cal.to_csv(results / "final_model_calibration.csv", index=False)
    lines = ["# Final model and calibration intervals (generated by "
             "`python -m polysafe.final_model`)", "",
             "PREREGISTRATION D12.1, specified after all model results were seen. The D7.2 "
             f"primary specification fitted once on all {len(y)} primary-cohort stays. "
             "Coefficients are per standard deviation of the design column (after median "
             "imputation); indicators are 1 when the named features are missing. **Its "
             "apparent performance is not reported**: all performance figures are the "
             "cross-validated ones in `results/models.md`.", ""]
    for name, t in coef.groupby("model", sort=False):
        lines += [f"## {name} (C = {t['C'].iloc[0]:g})", "",
                  "| Term | Coefficient | OR per SD | Median (imputation) | Mean | SD |",
                  "|---|---:|---:|---:|---:|---:|"]
        for r in t.itertuples():
            f = lambda v: "" if pd.isna(v) else f"{v:.4g}"  # noqa: E731
            lines.append(f"| {r.term} | {r.coefficient:+.4f} | {f(r.or_per_sd)} | "
                         f"{f(r.impute_median)} | {f(r.mean)} | {f(r.sd)} |")
        lines.append("")
    lines += ["## Calibration of the pooled out-of-fold predictions (95% patient-level BCa)",
              "", "| Model | Intercept | Slope |", "|---|---|---|"]
    label = {"lr_reduced": "Reduced LR", "lgbm": "LightGBM"}
    for r in cal.itertuples():
        which = "clinical + medication" if r.medication else "clinical only"
        lines.append(f"| {label[r.spec]}, {which} | {r.cal_intercept:+.3f} "
                     f"({r.intercept_lo:+.3f} to {r.intercept_hi:+.3f}) | {r.cal_slope:.3f} "
                     f"({r.slope_lo:.3f} to {r.slope_hi:.3f}) |")
    lines += ["", "Coverage of these intervals: not measured."]
    md = "\n".join(lines) + "\n"
    (results / "final_model.md").write_text(md, encoding="utf-8")
    print(md)
    return 0


def main(argv: list[str] | None = None) -> int:
    argparse.ArgumentParser(description="D12.1 final model.").parse_args(argv)
    return run(RESULTS)


if __name__ == "__main__":
    raise SystemExit(main())
