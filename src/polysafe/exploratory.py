"""D10.1 exploratory analysis: does a record-process marker explain the medication gain?

Specified after the section 8 and D8.1 results were seen; hypothesis-generating only.
U = 1 if a stay has a counted (D6.4) medication row with no drugname and a HICL code.

* E1: clinical-only + U against clinical-only (the stored primary predictions; same folds
  and tuning seeds, so the pair is matched);
* E2: clinical + medication + U against clinical-only + U.

Usage:
    python -m polysafe.exploratory    # writes results/exploratory_d10.csv and .md
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

import numpy as np
import pandas as pd

from polysafe import ascertain, bootstrap, features, models, review
from polysafe.tables import load

RESULTS = Path("results")
U = "u_unnamed_hicl_row"


def unnamed(med: pd.DataFrame) -> pd.Series:
    name = med["drugname"]
    return name.isna() | (name.astype(str).str.strip() == "")


def marker(med: pd.DataFrame, stays: pd.Index) -> pd.Series:
    """U per stay: 1/0 for stays with a medication record, NaN without one (D10.1)."""
    rows = ascertain.counting(med)
    rows = rows[unnamed(rows) & rows["drughiclseqno"].notna()]
    u = pd.Series(stays.isin(rows["patientunitstayid"].unique()).astype(float), index=stays,
                  name=U)
    u[~stays.isin(med["patientunitstayid"].unique())] = np.nan
    return u


def unnamed_only_share(med: pd.DataFrame, stays: pd.Index) -> pd.DataFrame:
    """For each exposure: exposed stays, and those exposed only through unnamed rows."""
    terms = review.REVIEW_DIR / "search_terms.txt"
    rows = ascertain.arm_rows(models.ARM, models.VARIANT, med, review.REVIEW_DIR, terms)
    rows = rows[rows["patientunitstayid"].isin(set(stays))]
    out = []
    for exposure in models.MEDICATION:
        r = rows[rows["exposure"] == exposure]
        exposed = set(r["patientunitstayid"])
        named = set(r.loc[~unnamed(r), "patientunitstayid"])
        out.append({"exposure": exposure, "exposed_stays": len(exposed),
                    "exposed_only_via_unnamed_rows": len(exposed - named)})
    return pd.DataFrame(out)


def md_table(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def run(results: Path, workers: int) -> int:
    X, y, groups = models.load_data(results)
    med = load("medication")
    X[U] = marker(med, X.index)
    base = models.specs([c for c in X.columns if c not in models.MED_COLS])[0]
    spec = models.Spec("lr_reduced_u", "lr", (*features.PRIMARY_LR_FEATURES, U),
                       features.PRIMARY_LR_INDICATORS)
    if base.clinical != features.PRIMARY_LR_FEATURES:
        raise RuntimeError("primary spec changed")
    pooled, _ = models.cross_validate(X, y, groups, [spec], workers=workers)
    preds = pd.read_csv(results / "model_predictions.csv").set_index("patientunitstayid")
    p_clin = preds.loc[X.index, "p_lr_reduced_clinical"].to_numpy(float)
    p_u, p_u_med = pooled[(spec.name, False)], pooled[(spec.name, True)]
    rows = []
    for key, label, p1, p0 in (("E1", "clinical + U vs clinical", p_u, p_clin),
                               ("E2", "clinical + medication + U vs clinical + U",
                                p_u_med, p_u)):
        ci = models.interval(bootstrap.delta_auroc(p1, p0, y), groups, bootstrap.N_BOOT)
        rows.append({"analysis": key, "comparison": label,
                     "auroc_without": bootstrap.auroc(p0, y),
                     "auroc_with": bootstrap.auroc(p1, y),
                     "dauroc": bootstrap.auroc(p1, y) - bootstrap.auroc(p0, y),
                     "lo": ci["lo"], "hi": ci["hi"], "bca_failed": ci["bca_failed"]})
    table = pd.DataFrame(rows)
    table.to_csv(results / "exploratory_d10.csv", index=False)
    lab = pd.read_csv(results / "labels_A.csv").set_index("patientunitstayid").loc[X.index]
    u = X[U]
    by_aki = pd.crosstab(u.fillna(-1).map({1.0: "U = 1", 0.0: "U = 0", -1.0: "no record"}),
                         lab["aki"].map({True: "AKI", False: "no AKI"}))
    hosp = lab.assign(u=u).groupby("hospitalid")["u"].mean()
    share = unnamed_only_share(med, X.index)
    primary = pd.read_csv(results / "model_comparison.csv").set_index("spec").loc["lr_reduced"]
    md = ["# D10.1 exploratory analysis (generated by `python -m polysafe.exploratory`)", "",
          "**Exploratory and hypothesis-generating; specified after the section 8 and D8.1 "
          "results were seen (PREREGISTRATION D10.1). It does not replace the primary "
          "result.** U = 1 if the stay has a counted medication row (D6.4) with no drugname "
          "and a HICL code.", "",
          f"Primary result: dAUROC {primary['dauroc']:+.3f} (95% BCa {primary['lo']:.3f} to "
          f"{primary['hi']:.3f}).", "",
          "| Analysis | Comparison | AUROC without | AUROC with | dAUROC (95% BCa) |",
          "|---|---|---:|---:|---|"]
    for r in table.itertuples():
        md.append(f"| {r.analysis} | {r.comparison} | {r.auroc_without:.3f} | "
                  f"{r.auroc_with:.3f} | {r.dauroc:+.3f} ({r.lo:.3f} to {r.hi:.3f}) |")
    md += ["", "## U by AKI status (stays)", "", md_table(by_aki.reset_index().rename(columns={"index": "U"})), "",
           f"Hospitals in the primary cohort: {hosp.notna().sum()}; share of stays with U = 1 "
           f"by hospital: median {hosp.median():.2f}, hospitals with U = 1 in every stay "
           f"{int((hosp == 1).sum())}, in no stay {int((hosp == 0).sum())}.", "",
           "## Exposed stays reached only through unnamed rows (HICL + gtc, primary)", "",
           md_table(share), "",
           "Reading stated in D10.1 before the run: if E2 stays near the primary gain, U "
           "does not explain it; if E2 falls towards 0 while E1 carries the gain, the "
           "record-process explanation is supported. Neither outcome is confirmatory."]
    text = "\n".join(md) + "\n"
    (results / "exploratory_d10.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="D10.1 exploratory analysis.")
    p.add_argument("--workers", type=int, default=max(1, min(6, (os.cpu_count() or 2) - 2)))
    args = p.parse_args(argv)
    return run(RESULTS, args.workers)


if __name__ == "__main__":
    raise SystemExit(main())
