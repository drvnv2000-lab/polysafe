"""Section 10 secondary analysis: propensity-adjusted drug-AKI associations (D11.1).

Associational only. For each agent (vancomycin, piperacillin-tazobactam, furosemide) and
the negative control (ondansetron): crude OR and the OR adjusted for the logit of a
propensity score built on the D4.4 reduced clinical set; patient-level percentile
bootstrap intervals with the propensity model refitted in every resample; overlap
diagnostics without trimming.

Usage:
    python -m polysafe.secondary    # writes results/secondary.csv and results/secondary.md
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression

from polysafe import ascertain, bootstrap, features, models
from polysafe.tables import load

RESULTS = Path("results")
AGENTS = ("vancomycin", "piperacillin-tazobactam", "furosemide")
NEGATIVE_CONTROL = "ondansetron"
N_BOOT = 2_000
SEED = bootstrap.SEED
EXPECTED_N = 651  # D11.1


def severity_design(X: pd.DataFrame) -> np.ndarray:
    """D4.4 reduced clinical set: median imputation, indicators, standardisation."""
    spec = models.specs(features.PRIMARY_LR_FEATURES)[0]
    z, _ = models.lr_design(X, X.iloc[:1], spec, medication=False)
    return z


def odds_ratios(z: np.ndarray, a: np.ndarray, y: np.ndarray) -> tuple[float, float, np.ndarray]:
    """(crude OR, propensity-adjusted OR, propensity scores)."""
    ps = LogisticRegression(C=1.0, max_iter=10_000).fit(z, a).predict_proba(z)[:, 1]
    crude = LogisticRegression(C=np.inf, max_iter=10_000).fit(a[:, None], y)
    adj = LogisticRegression(C=np.inf, max_iter=10_000).fit(
        np.column_stack([a, models.logit(ps)]), y)
    return float(np.exp(crude.coef_[0][0])), float(np.exp(adj.coef_[0][0])), ps


def overlap(ps: np.ndarray, a: np.ndarray) -> dict:
    e, u = ps[a == 1], ps[a == 0]
    q = lambda v: np.quantile(v, [0.05, 0.5, 0.95])  # noqa: E731
    return {"ps_exposed_p5_p50_p95": " / ".join(f"{v:.2f}" for v in q(e)),
            "ps_unexposed_p5_p50_p95": " / ".join(f"{v:.2f}" for v in q(u)),
            "exposed_outside_unexposed_range": int(((e < u.min()) | (e > u.max())).sum()),
            "unexposed_outside_exposed_range": int(((u < e.min()) | (u > e.max())).sum())}


def analyse(z: np.ndarray, a: np.ndarray, y: np.ndarray, groups: np.ndarray,
            n_boot: int = N_BOOT, seed: int = SEED) -> dict:
    crude, adj, ps = odds_ratios(z, a, y)
    ids, members = np.unique(groups, return_inverse=True)
    rows_of = [np.flatnonzero(members == i) for i in range(len(ids))]
    rng = np.random.default_rng(seed)
    boot = []
    for _ in range(n_boot):
        idx = np.concatenate([rows_of[i] for i in rng.integers(0, len(ids), len(ids))])
        if a[idx].all() or not a[idx].any() or y[idx].all() or not y[idx].any():
            continue
        boot.append(odds_ratios(z[idx], a[idx], y[idx])[:2])
    b = np.log(np.array(boot))
    lo, hi = np.exp(np.quantile(b, [0.025, 0.975], axis=0))
    return {"exposed": int(a.sum()), "events_exposed": int(y[a == 1].sum()),
            "events_unexposed": int(y[a == 0].sum()), "crude_or": crude,
            "crude_lo": lo[0], "crude_hi": hi[0], "adjusted_or": adj, "adjusted_lo": lo[1],
            "adjusted_hi": hi[1], "resamples_used": len(boot),
            "ps_c_statistic": bootstrap.auroc(ps, a)} | overlap(ps, a)


def run(results: Path) -> int:
    X, y, groups = models.load_data(results)
    med = load("medication")
    recorded = X.index.isin(med["patientunitstayid"].unique())
    X, y, groups = X[recorded], y[recorded], groups[recorded]
    if len(X) != EXPECTED_N:
        raise ValueError(f"D11.1 cohort: expected {EXPECTED_N} stays, found {len(X)}")
    tables, _ = ascertain.ascertain(med, X.index)
    exposure = tables[(models.ARM, models.VARIANT)]
    z = severity_design(X)
    rows = []
    for agent in (*AGENTS, NEGATIVE_CONTROL):
        a = exposure.loc[X.index, agent].to_numpy(int)
        rows.append({"agent": agent, "role": "negative control" if agent == NEGATIVE_CONTROL
                     else "pre-specified agent"} | analyse(z, a, y, groups))
        print(f"done {agent}", flush=True)
    table = pd.DataFrame(rows)
    table.to_csv(results / "secondary.csv", index=False)
    md = report(table, len(X), int(y.sum()))
    (results / "secondary.md").write_text(md, encoding="utf-8")
    print(md)
    return 0


def report(t: pd.DataFrame, n: int, events: int) -> str:
    lines = ["# Secondary analysis: drug-AKI associations (generated by "
             "`python -m polysafe.secondary`)", "",
             "PREREGISTRATION section 10 and D11.1. **Associational, not causal.** "
             f"{n} stays of the primary cohort with a medication record, {events} with AKI. "
             "Exposure: active medication order by T (D6.4), HICL + gtc. Adjustment: logit "
             "of a propensity score on the D4.4 reduced clinical set. 95% intervals: "
             f"patient-level percentile bootstrap, {N_BOOT:,} resamples, propensity model "
             "refitted in each. The analysis plan's details (D11.1) were fixed after the "
             "prediction results were seen and before any association was computed.", "",
             "| Agent | Role | Exposed (events) | Unexposed events | Crude OR (95% CI) | "
             "Adjusted OR (95% CI) | Resamples used |", "|---|---|---:|---:|---|---|---:|"]
    for r in t.itertuples():
        lines.append(f"| {r.agent} | {r.role} | {r.exposed} ({r.events_exposed}) | "
                     f"{r.events_unexposed} | {r.crude_or:.2f} ({r.crude_lo:.2f}-"
                     f"{r.crude_hi:.2f}) | {r.adjusted_or:.2f} ({r.adjusted_lo:.2f}-"
                     f"{r.adjusted_hi:.2f}) | {r.resamples_used} |")
    lines += ["", "## Overlap (no trimming)", "",
              "| Agent | PS c-statistic | PS exposed p5 / p50 / p95 | PS unexposed p5 / p50 / "
              "p95 | Exposed outside unexposed range | Unexposed outside exposed range |",
              "|---|---:|---|---|---:|---:|"]
    for r in t.itertuples():
        lines.append(f"| {r.agent} | {r.ps_c_statistic:.2f} | {r.ps_exposed_p5_p50_p95} | "
                     f"{r.ps_unexposed_p5_p50_p95} | {r.exposed_outside_unexposed_range} | "
                     f"{r.unexposed_outside_exposed_range} |")
    neg = t[t["role"] == "negative control"].iloc[0]
    lines += ["", f"Negative control (section 10): ondansetron adjusted OR "
              f"{neg.adjusted_or:.2f} ({neg.adjusted_lo:.2f}-{neg.adjusted_hi:.2f}). If it is "
              "of similar magnitude to the agents', the adjustment is inadequate and the agent "
              "estimates are not interpretable as drug effects."]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    argparse.ArgumentParser(description="Section 10 secondary analysis.").parse_args(argv)
    return run(RESULTS)


if __name__ == "__main__":
    raise SystemExit(main())
